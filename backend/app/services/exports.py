"""Study-material exports rendered in memory as Markdown, plain text or PDF.

Exports are generated on request and streamed back; nothing is written to disk, so there
is no stored file to overwrite and no user-controlled path to traverse.
"""

from __future__ import annotations

import html
import io
import re
from dataclasses import dataclass
from datetime import UTC, datetime

from app.models import Document, Question, Topic
from app.schemas import QuizResult

FORMATS = {"md": "text/markdown; charset=utf-8", "txt": "text/plain; charset=utf-8", "pdf": "application/pdf"}


@dataclass
class Block:
    kind: str  # h1 | h2 | h3 | p | li | meta | quote
    text: str


def _loc(label: str, start: int, end: int | None = None) -> str:
    if end and end != start:
        return f"{label.capitalize()}s {start}–{end}"
    return f"{label.capitalize()} {start}"


def _stamp() -> str:
    return datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")


def revision_notes(doc: Document, topics: list[Topic], detailed: bool) -> list[Block]:
    label = doc.unit_label
    blocks = [
        Block("h1", f"Revision notes: {doc.name}"),
        Block(
            "meta",
            f"Generated by StudyForge AI on {_stamp()} from {doc.original_filename}. "
            "Every statement below is quoted from the uploaded material (extractive, rule-based).",
        ),
    ]
    for t in topics:
        g = t.guide or {}
        blocks.append(Block("h2", f"{t.position + 1}. {t.title}"))
        blocks.append(
            Block(
                "meta",
                f"Source: {_loc(label, t.location_start, t.location_end)}"
                + (f" · Key terms: {', '.join(t.keywords[:6])}" if t.keywords else ""),
            )
        )
        if g.get("overview"):
            blocks.append(Block("h3", "Overview"))
            blocks.extend(Block("p", f"{o['text']} ({_loc(label, o['location'])})") for o in g["overview"])
        if g.get("definitions"):
            blocks.append(Block("h3", "Definitions"))
            blocks.extend(
                Block("li", f"**{d['term']}** — {d['definition']} ({_loc(label, d['location'])})")
                for d in g["definitions"]
            )
        points = g.get("key_points", [])
        if not detailed:
            points = sorted(points, key=lambda p: p.get("rank", 0))[:5]
            points.sort(key=lambda p: p["location"])
        if points:
            blocks.append(Block("h3", "Key points"))
            blocks.extend(Block("li", f"{p['text']} ({_loc(label, p['location'])})") for p in points)
        if detailed and g.get("relationships"):
            blocks.append(Block("h3", "Relationships"))
            blocks.extend(Block("li", f"{r['text']} ({_loc(label, r['location'])})") for r in g["relationships"])
        if detailed and g.get("examples"):
            blocks.append(Block("h3", "Examples and applications"))
            blocks.extend(Block("li", f"{e['text']} ({_loc(label, e['location'])})") for e in g["examples"])
        if g.get("revision"):
            blocks.append(Block("h3", "Quick revision"))
            blocks.extend(Block("li", r) for r in g["revision"])
    return blocks


TYPE_NAMES = {
    "mcq": "Multiple-choice questions",
    "short_answer": "Short-answer questions",
    "long_answer": "Long-answer questions",
}


def question_bank(
    doc: Document, questions: list[Question], topic_titles: dict[int, str], include_answers: bool
) -> list[Block]:
    label = doc.unit_label
    blocks = [
        Block("h1", f"Question bank: {doc.name}"),
        Block(
            "meta",
            f"Generated by StudyForge AI on {_stamp()}. {len(questions)} questions generated by rule-based "
            "templates from the uploaded material and checked by automatic validation rules.",
        ),
    ]
    numbered: list[tuple[int, Question]] = []
    n = 0
    for qtype in ("mcq", "short_answer", "long_answer"):
        group = [q for q in questions if q.question_type == qtype]
        if not group:
            continue
        blocks.append(Block("h2", TYPE_NAMES[qtype]))
        for q in group:
            n += 1
            numbered.append((n, q))
            topic = topic_titles.get(q.topic_id, "General")
            blocks.append(Block("p", f"**Q{n}.** {q.stem}"))
            blocks.append(Block("meta", f"{topic} · {q.difficulty} · {q.category}"))
            if q.options:
                blocks.extend(Block("li", f"({chr(65 + i)}) {o}") for i, o in enumerate(q.options))
    if include_answers and numbered:
        blocks.append(Block("h2", "Answer key"))
        for n, q in numbered:
            if q.question_type == "mcq":
                blocks.append(Block("p", f"**Q{n}.** ({chr(65 + q.correct_index)}) {q.answer_text}"))
            else:
                blocks.append(Block("p", f"**Q{n}.** Model answer:"))
                for line in q.answer_text.split("\n"):
                    blocks.append(Block("li" if line.startswith("- ") else "quote", line.removeprefix("- ")))
            blocks.append(Block("meta", f"{q.explanation} Source: {_loc(label, q.location_start, q.location_end)}."))
    return blocks


def quiz_report(result: QuizResult, unit_labels: dict[str, str]) -> list[Block]:
    blocks = [
        Block("h1", f"Quiz results: {result.title}"),
        Block(
            "meta",
            f"Submitted {result.submitted_at:%Y-%m-%d %H:%M UTC}. Score {result.correct_count}/{result.total} "
            f"({result.score_percent}%), {result.unanswered_count} unanswered.",
        ),
        Block("h2", "Topic breakdown"),
    ]
    blocks.extend(Block("li", f"{t.topic_title}: {t.correct}/{t.total}") for t in result.topic_breakdown)
    blocks.append(Block("h2", "Questions"))
    for item in result.items:
        status = {"correct": "Correct", "incorrect": "Incorrect", "unanswered": "Unanswered"}[item.status]
        blocks.append(Block("p", f"**Q{item.position + 1}.** {item.stem} — {status}"))
        for i, o in enumerate(item.options):
            marks = []
            if i == item.correct_index:
                marks.append("correct answer")
            if i == item.selected_index:
                marks.append("your answer")
            blocks.append(Block("li", f"({chr(65 + i)}) {o}" + (f"  [{', '.join(marks)}]" if marks else "")))
        label = unit_labels.get(item.document_id, "page")
        blocks.append(
            Block("meta", f"{item.explanation} Source: {_loc(label, item.location_start, item.location_end)}.")
        )
    return blocks


# ------------------------------------------------------------------------ renderers

_BOLD = re.compile(r"\*\*(.+?)\*\*")


def to_markdown(blocks: list[Block]) -> str:
    out: list[str] = []
    prev = None
    for b in blocks:
        if b.kind == "li":
            if prev != "li":
                out.append("")
            out.append(f"- {b.text}")
        elif b.kind in ("h1", "h2", "h3"):
            out.extend(["", f"{'#' * int(b.kind[1])} {b.text}", ""])
        elif b.kind == "meta":
            out.extend(["", f"_{b.text}_", ""])
        elif b.kind == "quote":
            out.extend(["", f"> {b.text}", ""])
        else:
            out.extend(["", b.text, ""])
        prev = b.kind
    text = "\n".join(out)
    return re.sub(r"\n{3,}", "\n\n", text).strip() + "\n"


def to_text(blocks: list[Block]) -> str:
    out: list[str] = []
    for b in blocks:
        text = _BOLD.sub(r"\1", b.text)
        if b.kind == "h1":
            out.extend([text.upper(), "=" * min(len(text), 78), ""])
        elif b.kind == "h2":
            out.extend(["", text, "-" * min(len(text), 78)])
        elif b.kind == "h3":
            out.extend(["", f"{text}:"])
        elif b.kind == "li":
            out.append(f"  * {text}")
        elif b.kind == "meta":
            out.append(f"  ({text})")
        else:
            out.extend(["", text])
    return "\n".join(out).strip() + "\n"


def to_pdf(blocks: list[Block]) -> bytes:
    import fitz

    parts: list[str] = []
    in_list = False
    for b in blocks:
        text = _BOLD.sub(r"<b>\1</b>", html.escape(b.text))
        if b.kind == "li":
            if not in_list:
                parts.append("<ul>")
                in_list = True
            parts.append(f"<li>{text}</li>")
            continue
        if in_list:
            parts.append("</ul>")
            in_list = False
        if b.kind in ("h1", "h2", "h3"):
            parts.append(f"<{b.kind}>{text}</{b.kind}>")
        elif b.kind == "meta":
            parts.append(f'<p class="meta">{text}</p>')
        elif b.kind == "quote":
            parts.append(f"<blockquote>{text}</blockquote>")
        else:
            parts.append(f"<p>{text}</p>")
    if in_list:
        parts.append("</ul>")
    css = (
        "body{font-family:sans-serif;font-size:10pt;color:#1e293b;} h1{font-size:17pt;color:#1e1b4b;margin-bottom:4pt;}"
        "h2{font-size:13pt;color:#312e81;margin-top:14pt;} h3{font-size:11pt;margin-top:8pt;margin-bottom:2pt;}"
        "p{margin:3pt 0;} li{margin:2pt 0;} .meta{font-size:8.5pt;color:#64748b;} blockquote{margin-left:12pt;}"
    )
    story = fitz.Story(html="".join(parts), user_css=css)
    buffer = io.BytesIO()
    writer = fitz.DocumentWriter(buffer)
    mediabox = fitz.paper_rect("a4")
    where = mediabox + (50, 50, -50, -50)
    more = True
    pages = 0
    while more and pages < 500:
        device = writer.begin_page(mediabox)
        more, _ = story.place(where)
        story.draw(device)
        writer.end_page()
        pages += 1
    writer.close()
    return buffer.getvalue()


def render(blocks: list[Block], fmt: str) -> bytes:
    if fmt == "md":
        return to_markdown(blocks).encode("utf-8")
    if fmt == "txt":
        return to_text(blocks).encode("utf-8")
    return to_pdf(blocks)


def export_filename(name: str, suffix: str, fmt: str) -> str:
    slug = re.sub(r"[^A-Za-z0-9]+", "-", name).strip("-").lower()[:60] or "studyforge"
    return f"{slug}-{suffix}.{fmt}"
